// GET /api/transactions/analysis
// Access: user role
// Category spending breakdown + transactions where another active card would have earned more
exports.getTransAnalysis = async (req, res, next) => {
  try {
    const [cards, transactions] = await Promise.all([
      // All of the user's cards (closed ones too, since a transaction may have used one)
      Card.find({ userId: req.userId })
        .select('cardName network last4 status cardProductId')
        .populate('cardProductId', 'baseRate categoryRates')
        .lean(),
      Transaction.find({ userId: req.userId, status: { $in: COUNTED_STATUSES } })
        .select('cardId merchant category amount transactionDate status')
        .sort({ transactionDate: -1, _id: -1 })
        .lean()
    ]);

    const cardsById = new Map(cards.map((c) => [String(c._id), c]));
    const activeCards = cards.filter((c) => c.status === 'active' && c.cardProductId);

    // Best active card per category, computed once per category
    const bestByCategory = new Map();
    const bestFor = (category) => {
      if (!bestByCategory.has(category)) {
        let best = null;
        for (const card of activeCards) {
          const rate = rateFor(card.cardProductId, category);
          if (!best || rate > best.rate) best = { card, rate };
        }
        bestByCategory.set(category, best);
      }
      return bestByCategory.get(category);
    };

    const totalsByCategory = new Map();
    let totalSpend = 0;
    let totalMissedRewards = 0;
    const missed = [];

    for (const tx of transactions) {
      // Category breakdown
      const t = totalsByCategory.get(tx.category) || { category: tx.category, totalSpend: 0, transactions: 0 };
      t.totalSpend += tx.amount;
      t.transactions += 1;
      totalsByCategory.set(tx.category, t);
      totalSpend += tx.amount;

      // Right-card check
      const usedCard = cardsById.get(String(tx.cardId));
      if (!usedCard || !usedCard.cardProductId) continue; // card or product deleted

      const rateUsed = rateFor(usedCard.cardProductId, tx.category);
      const best = bestFor(tx.category);

      if (best && best.rate > rateUsed && String(best.card._id) !== String(usedCard._id)) {
        const missedRewards = round2(tx.amount * (best.rate - rateUsed));
        totalMissedRewards += missedRewards;
        missed.push({
          transactionId: tx._id,
          merchant: tx.merchant,
          category: tx.category,
          amount: tx.amount,
          transactionDate: tx.transactionDate,
          status: tx.status,
          cardUsed: cardSummary(usedCard, rateUsed),
          betterCard: cardSummary(best.card, best.rate),
          missedRewards
        });
      }
    }

    const categoryBreakdown = [...totalsByCategory.values()]
      .map((c) => ({
        category: c.category,
        totalSpend: round2(c.totalSpend),
        transactions: c.transactions,
        percentOfSpend: totalSpend ? round2((c.totalSpend / totalSpend) * 100) : 0
      }))
      .sort((a, b) => b.totalSpend - a.totalSpend);

    res.status(200).json({
      totalSpend: round2(totalSpend),
      categoryBreakdown,
      rightCardAnalysis: {
        totalTransactions: transactions.length,
        missedTransactions: missed.length,
        totalMissedRewards: round2(totalMissedRewards),
        transactions: missed // newest first
      }
    });
  } catch (err) {
    next(err);
  }
};

// /api/transactions/deleteTrans
exports.deleteTrans = async (req, res, next) => {
    try{
        // Deletes card using the cardID input parameter we want to delete
        const deletedTrans = await Transaction.deleteOne({_id: req.params.transId, userId: req.userId});
        if (deletedTrans.deletedCount === 0) {
            return res.status(404).json({ error: "Can't delete, transaction does not exist." });
        }
        res.status(200).json(deletedTrans);
    } catch (err) {
        next(err);
    }
};