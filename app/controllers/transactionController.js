// Declined transactions never count as spend
const COUNTED_STATUSES = ['pending', 'posted'];

const round2 = (n) => Math.round((n || 0) * 100) / 100;

// Same logic as CardProduct.rateFor, for lean (plain object) products.
// Case-insensitive so product key "dining" matches category "Dining".
const rateFor = (product, category) => {
  if (!product) return null;
  const key = String(category).toLowerCase();
  for (const [k, v] of Object.entries(product.categoryRates || {})) {
    if (k.toLowerCase() === key) return v;
  }
  return product.baseRate;
};

const cardSummary = (card, rate) => ({
  cardId: card._id,
  cardName: card.cardName,
  network: card.network,
  last4: card.last4,
  rewardRate: rate
});


